// Attribute-free native operation construction. Regenerate from native declarations
// when the dialect catalog changes; semantic attributes use explicit adapters.
use crate::{
    ops::*,
    pliron::{
        context::{Context, Ptr},
        op::Op,
        operation::Operation,
        r#type::TypeHandle,
        value::Value,
    },
};

pub(super) fn build(
    ctx: &mut Context,
    name: &str,
    results: Vec<TypeHandle>,
    operands: Vec<Value>,
) -> Option<Ptr<Operation>> {
    let info = match name {
        "stablehlo.abs" => AbsOp::get_concrete_op_info(),
        "stablehlo.add" => AddOp::get_concrete_op_info(),
        "stablehlo.after_all" => AfterAllOp::get_concrete_op_info(),
        "stablehlo.and" => AndOp::get_concrete_op_info(),
        "stablehlo.async_done" => AsyncDoneOp::get_concrete_op_info(),
        "stablehlo.async_start" => AsyncStartOp::get_concrete_op_info(),
        "stablehlo.atan2" => Atan2Op::get_concrete_op_info(),
        "stablehlo.bitcast_convert" => BitcastConvertOp::get_concrete_op_info(),
        "stablehlo.cbrt" => CbrtOp::get_concrete_op_info(),
        "stablehlo.ceil" => CeilOp::get_concrete_op_info(),
        "stablehlo.clamp" => ClampOp::get_concrete_op_info(),
        "stablehlo.complex" => ComplexOp::get_concrete_op_info(),
        "stablehlo.convert" => ConvertOp::get_concrete_op_info(),
        "stablehlo.cosine" => CosineOp::get_concrete_op_info(),
        "stablehlo.count_leading_zeros" => CountLeadingZerosOp::get_concrete_op_info(),
        "stablehlo.create_token" => CreateTokenOp::get_concrete_op_info(),
        "stablehlo.divide" => DivideOp::get_concrete_op_info(),
        "stablehlo.dynamic_pad" => DynamicPadOp::get_concrete_op_info(),
        "stablehlo.dynamic_reshape" => DynamicReshapeOp::get_concrete_op_info(),
        "stablehlo.dynamic_update_slice" => DynamicUpdateSliceOp::get_concrete_op_info(),
        "stablehlo.exp2" => Exp2Op::get_concrete_op_info(),
        "stablehlo.exponential" => ExponentialOp::get_concrete_op_info(),
        "stablehlo.exponential_minus_one" => ExponentialMinusOneOp::get_concrete_op_info(),
        "stablehlo.floor" => FloorOp::get_concrete_op_info(),
        "stablehlo.imag" => ImagOp::get_concrete_op_info(),
        "stablehlo.is_finite" => IsFiniteOp::get_concrete_op_info(),
        "stablehlo.log" => LogOp::get_concrete_op_info(),
        "stablehlo.log2" => Log2Op::get_concrete_op_info(),
        "stablehlo.log_plus_one" => LogPlusOneOp::get_concrete_op_info(),
        "stablehlo.logistic" => LogisticOp::get_concrete_op_info(),
        "stablehlo.maximum" => MaximumOp::get_concrete_op_info(),
        "stablehlo.minimum" => MinimumOp::get_concrete_op_info(),
        "stablehlo.multiply" => MultiplyOp::get_concrete_op_info(),
        "stablehlo.negate" => NegateOp::get_concrete_op_info(),
        "stablehlo.not" => NotOp::get_concrete_op_info(),
        "stablehlo.optimization_barrier" => OptimizationBarrierOp::get_concrete_op_info(),
        "stablehlo.or" => OrOp::get_concrete_op_info(),
        "stablehlo.partition_id" => PartitionIdOp::get_concrete_op_info(),
        "stablehlo.popcnt" => PopulationCountOp::get_concrete_op_info(),
        "stablehlo.power" => PowerOp::get_concrete_op_info(),
        "stablehlo.real" => RealOp::get_concrete_op_info(),
        "stablehlo.real_dynamic_slice" => RealDynamicSliceOp::get_concrete_op_info(),
        "stablehlo.remainder" => RemainderOp::get_concrete_op_info(),
        "stablehlo.replica_id" => ReplicaIdOp::get_concrete_op_info(),
        "stablehlo.reshape" => ReshapeOp::get_concrete_op_info(),
        "stablehlo.round_nearest_afz" => RoundNearestAfzOp::get_concrete_op_info(),
        "stablehlo.round_nearest_even" => RoundNearestEvenOp::get_concrete_op_info(),
        "stablehlo.rsqrt" => RsqrtOp::get_concrete_op_info(),
        "stablehlo.select" => SelectOp::get_concrete_op_info(),
        "stablehlo.shift_left" => ShiftLeftOp::get_concrete_op_info(),
        "stablehlo.shift_right_arithmetic" => ShiftRightArithmeticOp::get_concrete_op_info(),
        "stablehlo.shift_right_logical" => ShiftRightLogicalOp::get_concrete_op_info(),
        "stablehlo.sign" => SignOp::get_concrete_op_info(),
        "stablehlo.sine" => SineOp::get_concrete_op_info(),
        "stablehlo.sqrt" => SqrtOp::get_concrete_op_info(),
        "stablehlo.subtract" => SubtractOp::get_concrete_op_info(),
        "stablehlo.tan" => TanOp::get_concrete_op_info(),
        "stablehlo.tanh" => TanhOp::get_concrete_op_info(),
        "stablehlo.tuple" => TupleOp::get_concrete_op_info(),
        "stablehlo.uniform_dequantize" => UniformDequantizeOp::get_concrete_op_info(),
        "stablehlo.uniform_quantize" => UniformQuantizeOp::get_concrete_op_info(),
        "stablehlo.xor" => XorOp::get_concrete_op_info(),
        _ => return None,
    };
    Some(Operation::new(ctx, info, results, operands, vec![], 0))
}
